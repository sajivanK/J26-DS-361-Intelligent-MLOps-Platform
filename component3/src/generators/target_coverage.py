"""Target-slice coverage evaluation for synthetic tabular records."""

from dataclasses import dataclass
import pandas as pd

from component3.src.contracts.safe_slice_evaluator import (
    evaluate_slice_rule,
)


@dataclass(frozen=True)
class TargetCoverageResult:
    """Summary of generated records matching a C2 slice rule."""

    total_rows: int
    matching_rows: int
    non_matching_rows: int
    coverage: float
    slice_rule: str

    def to_dict(self) -> dict:
        return {
            "total_rows": self.total_rows,
            "matching_rows": self.matching_rows,
            "non_matching_rows": self.non_matching_rows,
            "coverage": self.coverage,
            "slice_rule": self.slice_rule,
        }


def evaluate_target_coverage(
    synthetic_data: pd.DataFrame,
    slice_rule: str,
) -> TargetCoverageResult:
    """Evaluate how many generated synthetic records satisfy a restricted C2 slice rule.

    Parameters
    ----------
    synthetic_data : pd.DataFrame
        Synthetic tabular dataset generated by a model.
    slice_rule : str
        Restricted C2 slice expression (e.g. 'race == 2').

    Returns
    -------
    TargetCoverageResult
        Structured metrics summarizing target-slice coverage.
    """
    mask = evaluate_slice_rule(synthetic_data, slice_rule)

    total_rows = len(synthetic_data)
    matching_rows = int(mask.sum())
    non_matching_rows = total_rows - matching_rows
    coverage = float(matching_rows / total_rows) if total_rows > 0 else 0.0

    return TargetCoverageResult(
        total_rows=total_rows,
        matching_rows=matching_rows,
        non_matching_rows=non_matching_rows,
        coverage=coverage,
        slice_rule=slice_rule.strip(),
    )
